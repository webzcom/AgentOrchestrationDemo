using AgentDemo.Core;
using AgentDemo.Tools;

namespace AgentDemo.Agents;

/// <summary>
/// Tester: compiles and runs the Coder's code against known test cases.
///
/// Notice: this agent uses NO model at all. It's plain, deterministic code with tools.
/// Not every step in an agent workflow needs an LLM — the most reliable checks
/// (build, tests, linters) are usually ordinary programs. Let the model generate;
/// let real tools verify.
/// </summary>
public sealed class TesterAgent(WorkspaceTools tools) : IAgent
{
    public string Name => "Tester";
    public ConsoleColor Color => ConsoleColor.Magenta;

    // input, expected
    private static readonly (string? Input, bool Expected)[] Cases =
    [
        ("racecar", true),
        ("hello", false),
        ("A man, a plan, a canal: Panama", true),
        ("No 'x' in Nixon", true),
        ("ab", false),
        ("", true),
        (null, true),
    ];

    public async Task<AgentResult> RunAsync(TaskContext ctx, CancellationToken ct = default)
    {
        tools.WriteFile("Workspace.csproj", ProjectFile);
        tools.WriteFile("Program.cs", BuildTestHarness());

        var (exit, output) = await tools.RunDotnetAsync("run", ct);   // ← tool call: real build + run
        ctx.TestReport = output;

        if (exit == 0)
        {
            Trace.Detail("Test output", output);
            return new AgentResult(true, $"All {Cases.Length} tests passed.");
        }

        Trace.Detail("Test output", Shorten(output), force: true);
        var failed = output.Split('\n').Count(l => l.StartsWith("FAIL"));
        return new AgentResult(false, failed > 0
            ? $"{failed} of {Cases.Length} tests failed."
            : "Build failed (see output).");
    }

    private static string BuildTestHarness()
    {
        static string Lit(string? s) => s is null ? "null" : "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        var rows = string.Join(",\n    ", Cases.Select(c => $"({Lit(c.Input)}, {c.Expected.ToString().ToLowerInvariant()})"));

        return $$"""
            // Auto-generated by TesterAgent. Do not edit — it is rewritten on every run.
            var cases = new (string? Input, bool Expected)[]
            {
                {{rows}}
            };
            var failures = 0;
            foreach (var (input, expected) in cases)
            {
                var actual = Solution.IsPalindrome(input);
                var label = input is null ? "null" : $"\"{input}\"";
                if (actual == expected) Console.WriteLine($"PASS  IsPalindrome({label}) == {expected}");
                else { failures++; Console.WriteLine($"FAIL  IsPalindrome({label}) expected {expected} but got {actual}"); }
            }
            return failures == 0 ? 0 : 1;
            """;
    }

    private const string ProjectFile = """
        <Project Sdk="Microsoft.NET.Sdk">
          <PropertyGroup>
            <OutputType>Exe</OutputType>
            <TargetFramework>net8.0</TargetFramework>
            <ImplicitUsings>enable</ImplicitUsings>
            <Nullable>enable</Nullable>
          </PropertyGroup>
        </Project>
        """;

    private static string Shorten(string s)
    {
        var lines = s.Split('\n');
        return lines.Length <= 20 ? s : string.Join('\n', lines.Take(20)) + $"\n... ({lines.Length - 20} more lines)";
    }
}
